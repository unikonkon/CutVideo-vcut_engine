def blank_journey():
    return {**{k: (list(v) if isinstance(v, list) else v)
               for k, v in JOURNEY.items()}, "stops": []}


def _journey(v):
    """แผนที่หนึ่งชุด — เส้นทาง · หมุด · หน้าตา

    stops ไม่ถูกจัดเรียงใหม่ตามระยะทาง **ลำดับในไฟล์คือลำดับการเดิน** เพราะสิ่ง
    ที่กำหนดว่าคนเดินจากไหนไปไหนคือลำดับ ไม่ใช่ตัวเลข dist (ซึ่งเป็นแค่ตัวเลข
    ที่เอาไปแสดง และเส้นทางที่วนกลับจะมี dist ลดลงได้โดยไม่ผิดอะไร)
    """
    if not isinstance(v, dict):
        return blank_journey()
    out = _pick(v, {k: b for k, b in JOURNEY.items()
                    if not isinstance(b, list)}, J_LIMITS)
    box = v.get("box")
    if isinstance(box, (list, tuple)) and len(box) >= 2:
        try:
            out["box"] = [max(1.0, float(box[0])), max(1.0, float(box[1]))]
        except (TypeError, ValueError):
            out["box"] = list(JOURNEY["box"])
    else:
        out["box"] = list(JOURNEY["box"])
    stops = v.get("stops")
    out["stops"] = [_stop(s) for s in stops if isinstance(s, dict)] \
        if isinstance(stops, list) else []
    return out


def load(ctx):
    d = read_json(path(ctx)) or {}
    out = blank()
    if not d:
        return out
    clips = d.get("clips") or {}
    if isinstance(clips, dict):
        out["clips"] = {str(k): _pick(v, CLIP)
                        for k, v in clips.items() if isinstance(v, dict)}
    if isinstance(d.get("overlays"), list):
        out["overlays"] = [_overlay(o) for o in d["overlays"] if isinstance(o, dict)]
    if d.get("music") is not None:
        out["music"] = _music_list(d["music"])
    if d.get("journey") is not None:
        out["journey"] = _journey(d["journey"])

    t = d.get("text") or {}
    if isinstance(t, dict):
        out["text"]["sub"] = _pick(t.get("sub"), TEXT)
        out["text"]["plate"] = _pick(t.get("plate"), PLATE)
        if isinstance(t.get("boxes"), dict):
            out["text"]["boxes"] = {str(k): _pick(v, TEXT)
                                    for k, v in t["boxes"].items()
                                    if isinstance(v, dict)}

    if isinstance(d.get("shapes"), list):
        out["shapes"] = [_shape(s) for s in d["shapes"] if isinstance(s, dict)]

    if isinstance(d.get("style"), dict):
        out["style"] = _pick(d["style"], STYLE)
    if isinstance(d.get("texts"), list):
        out["texts"] = [_text(t) for t in d["texts"] if isinstance(t, dict)]
    if isinstance(d.get("auto_sub"), dict):
        out["auto_sub"] = _pick(d["auto_sub"], AUTO_SUB)
    return out


