def _atempo(speed):
    """atempo รับได้ทีละ 0.5–2.0 เท่านั้น — นอกช่วงต้องซอยเป็นหลายทอด

    ทำไมไม่ใช้ asetrate (เปลี่ยนอัตราสุ่มตัวอย่าง) ซึ่งสั้นกว่า: asetrate เปลี่ยน
    *ระดับเสียง* ไปด้วย สโลว์โม 0.4 เท่าจะทำให้เสียงคนกลายเป็นเสียงผี ส่วน atempo
    ยืดเวลาโดยคงระดับเสียงไว้ ซึ่งคือสิ่งที่คนคาดหวังจากปุ่มชื่อ "ความเร็ว"
    """
    out, r = [], float(speed)
    while r < 0.5:
        out.append("atempo=0.5")
        r /= 0.5
    while r > 2.0:
        out.append("atempo=2.0")
        r /= 2.0
    if abs(r - 1.0) > 1e-4:
        out.append(f"atempo={r:.6f}")
    return out


def _zoom_pair(f):
    """(ซูมตอนเริ่ม, ซูมตอนจบ, เดินไหม) — ตัวเดียวที่ตีความ zoom/zoom_to/pan

    อยู่ที่เดียวเพราะทั้ง seg_vfilter กับหน้าเว็บต้องตอบคำถามเดียวกันว่า
    "ชิ้นนี้กล้องเดินหรือค้าง" ถ้าตีความคนละที่ วันหนึ่งพรีวิวกับไฟล์จะไม่ตรงกัน
    """
    z0 = float(f.get("zoom", 1.0) or 1.0)
    z1 = float(f.get("zoom_to", 0.0) or 0.0)
    if z1 <= 1e-6:                 # 0 = ไม่เดิน
        z1 = z0
    elif z1 < 1.0:                 # ต่ำกว่าเต็มเฟรมไม่มีความหมาย
        z1 = 1.0
    pan = str(f.get("pan", "") or "")
    room = max(z0, z1) > 1.0 + 1e-6
    moving = room and (abs(z1 - z0) > 1e-4 or pan in ("l", "r", "u", "d"))
    return z0, z1, moving


def _kenburns(f, ctx, frames, W, H):
    """zoompan ที่ไล่ซูม/ไถลกรอบตามเวลา

    **ต้องอยู่ก่อน setpts เสมอ** — zoompan สร้างไทม์ไลน์ของตัวเองที่อัตรา fps
    แล้วทิ้ง PTS ขาเข้า ถ้าวางไว้หลัง setpts มันจะลบผลของความเร็วทิ้งเงียบ ๆ
    วัดจริง: ช็อต 90 เฟรมตั้ง speed=2 ควรได้เฟรม 0–89 ย่อลงเหลือ 45 เฟรม
    แต่ได้เฟรม 0–44 ที่ความเร็วปกติแทน — ครึ่งหลังของช็อตหายไปโดยไม่มีอะไรฟ้อง
    (จำนวนเฟรมยังถูกต้อง 45 เพราะท้ายสาย trim ให้ ด่านความยาวจึงจับไม่ได้)
    """
    z0, z1, _ = _zoom_pair(f)
    # ตัวหารคือจำนวนเฟรม *ขาเข้า* (ก่อนถูกย่อด้วยความเร็ว) ไม่ใช่เฟรมขาออก
    src = max(2, int(round(frames * float(f.get("speed", 1.0) or 1.0))))
    prog = rf"min(1\,on/{src - 1})"
    zex = f"{z0:.4f}" if abs(z1 - z0) < 1e-4 \
        else f"{z0:.4f}+({z1 - z0:.4f})*{prog}"
    # ระยะที่เลื่อนได้ = ภาพเต็มลบกรอบที่มองเห็น · zoom = ค่าซูมของเฟรมนั้น
    sx, sy = "(iw-iw/zoom)", "(ih-ih/zoom)"
    x, y = f"{sx}/2", f"{sy}/2"
    pan = str(f.get("pan", "") or "")
    if pan == "r":
        x = f"{sx}*{prog}"
    elif pan == "l":
        x = f"{sx}*(1-{prog})"
    elif pan == "d":
        y = f"{sy}*{prog}"
    elif pan == "u":
        y = f"{sy}*(1-{prog})"
    return (f"zoompan=z='{zex}':x='{x}':y='{y}':d=1:s={W}x{H}"
            f":fps={ctx.get('video.fps', '60000/1001')}")


def seg_vfilter(f, ctx, frames):
    """ฟิลเตอร์ภาพของชิ้นที่ถูกแต่ง — ออกมาเป็น `frames` เฟรมพอดีเสมอ

    ท้ายสายเหมือนขั้น 3 ทุกตัว (tpad → fps → trim ตามจำนวนเฟรม) เพราะเหตุผล
    เดียวกันเป๊ะ: ตัดด้วยจำนวนเฟรมไม่ใช่ตามเวลา ไม่งั้นได้ภาพยาวเกินเสียงหนึ่งเฟรม
    (ดู render.segment_vfilter สำหรับเหตุผลเต็ม)
    """
    W = int(ctx.get("video.width", 1920))
    H = int(ctx.get("video.height", 1080))
    parts = []
    z = float(f.get("zoom", 1.0))
    moving = _zoom_pair(f)[2]
    if moving:
        parts.append(_kenburns(f, ctx, frames, W, H))
    sp = float(f.get("speed", 1.0))
    if abs(sp - 1.0) > 1e-6:
        parts.append(f"setpts=PTS/{sp:.6f}")
    if not moving and z > 1.0 + 1e-6:
        # ขยายแล้วครอบกลับให้เท่าเดิม = ดันเข้าโดยกรอบภาพไม่เปลี่ยน · ขนาดต้องเป็น
        # เลขคู่ ไม่งั้น yuv420p ซึ่งเก็บสีครึ่งความละเอียดจะปัดเศษแล้วภาพเพี้ยน
        #
        # ทางนี้เร็วกว่า zoompan มาก (คำนวณครั้งเดียว ไม่ใช่ทุกเฟรม) จึงเก็บไว้
        # สำหรับซูมค้าง แทนที่จะให้ทุกช็อตวิ่งผ่าน zoompan เหมือนกันหมด
        flags = ctx.get("video.scale_flags", "lanczos")
        parts.append(f"scale=w=ceil(iw*{z:.4f}/2)*2:h=ceil(ih*{z:.4f}/2)*2:flags={flags}")
        parts.append(f"crop={W}:{H}")
    g = str(f.get("grade", "") or "")
    if g in GRADE_VF:
        parts.append(GRADE_VF[g])
    # ── ภาพกระตุก ──
    #
    # หลังโทนสี เพราะมันคือ "สัญญาณเสีย" ที่เกิดกับภาพที่แต่งเสร็จแล้ว ไม่ใช่สีของภาพ
    gl = float(f.get("glitch", 0.0) or 0.0)
    if gl > 1e-6:
        period = 1.0 / float(f.get("glitch_hz", 1.4) or 1.4)
        # ติดสั้น ๆ เป็นจังหวะ ไม่ใช่ค้างทั้งช็อต — ค้างแล้วตาอ่านว่าไฟล์เสีย
        on = min(0.10, period * 0.28)
        gate = rf"lt(mod(t\,{period:.4f})\,{on:.4f})"
        parts.append(f"rgbashift=rh=-{int(round(28 * gl))}"
                     f":bh={int(round(28 * gl))}:enable='{gate}'")
        if gl > 0.45:
            parts.append(f"noise=alls={int(round(60 * gl))}:allf=t+u:enable='{gate}'")
    # ── เบลอหัว-ท้าย ──
    #
    # ท้ายสุดของชั้นภาพ เพราะกล้องที่สะบัดทำให้ *ทุกอย่าง* ในเฟรมเบลอ รวมทั้งสีที่
    # เพิ่งแต่งกับสัญญาณที่เพิ่งกระตุก ไม่ใช่เบลอภาพดิบแล้วเอาของคมมาแปะทับ
    wp = float(f.get("whip", 0.0) or 0.0)
    if wp > 1e-6:
        dur = frames / _fps(ctx)
        d = min(0.12, dur / 3.0)     # ช็อตสั้นมากต้องเบลอสั้นตาม ไม่งั้นเบลอทั้งช็อต
        sig = 18.0 * wp
        parts.append(rf"gblur=sigma={sig:.2f}:enable='lt(t\,{d:.3f})'")
        parts.append(rf"gblur=sigma={sig:.2f}:enable='gt(t\,{dur - d:.3f})'")
    parts.append("tpad=stop_mode=clone:stop_duration=0.5")
    parts.append(f"fps={ctx.get('video.fps', '60000/1001')}")
    parts.append(f"trim=end_frame={int(frames)}")
    parts.append("setpts=PTS-STARTPTS")
    parts.append("setsar=1,format=yuv420p")
    return ",".join(parts)


def pair_path(ctx, f):
    """ไฟล์ของอีกครึ่งจอ — None = ไม่ได้เปิด หรือเปิดแต่หาไฟล์ไม่เจอ

    ตอบ None ทั้งสองกรณีโดยตั้งใจ: ตัวเรียกทุกตัวต้องการรู้แค่ "แบ่งจอได้ไหม"
    ส่วนการบอกว่า *ทำไมไม่ได้* เป็นงานของ plan() ซึ่งเห็นทั้งไทม์ไลน์และเตือนได้
    ครั้งเดียวจบ แทนที่จะเตือนซ้ำทุกครั้งที่มีคนถามชื่อไฟล์
    """
    if not _on_split(f):
        return None
    name = str(f.get("split_with", "") or "").strip()
    p = Path(name).expanduser()
    p = p if p.is_absolute() else ctx.source / name
    return p if p.is_file() else None


def _half(v):
    """ครึ่งหนึ่งที่ยังเป็นเลขคู่ — yuv420p เก็บสีครึ่งความละเอียด ด้านคี่จึงไม่ได้"""
    return max(2, int(v) // 2 // 2 * 2)


def seg_complex(ctx, f, frames):
    """สายฟิลเตอร์ของชิ้นที่แบ่งจอ — สองอินพุตเข้า หนึ่งภาพหนึ่งเสียงออก

    **ย่อสองครึ่งก่อน แล้วค่อยเอาสายเดิมทั้งเส้นไปต่อท้ายภาพที่ประกอบแล้ว**

    ทำแบบนี้แล้วทุกอย่างที่ขั้น 5 ทำได้อยู่แล้ว (สโลว์โม · ซูม · กล้องเคลื่อน ·
    โทนสี · กระตุก · เบลอหัวท้าย) ยังทำงานกับชิ้นที่แบ่งจอได้ครบโดยไม่ต้องเขียน
    ใหม่สักตัว — และท้ายสายที่บังคับจำนวนเฟรมก็ยังเป็นตัวเดิม ความยาวจึงเป๊ะเท่าเดิม

    ราคาที่จ่ายคือซูมเข้าไปในภาพที่ *แบ่งแล้ว* ไม่ใช่ซูมแต่ละครึ่งแยกกัน ซึ่งตรง
    กับที่ตาคาดหวังจากคำว่า "ซูม" บนชิ้นนี้อยู่แล้ว
    """
    W = int(ctx.get("video.width", 1920))
    H = int(ctx.get("video.height", 1080))
    mode = str(f.get("split", "") or "")
    hw, hh = (_half(W), H) if mode == "h" else (W, _half(H))
    flags = ctx.get("video.scale_flags", "lanczos")
    dur = frames / _fps(ctx)

    # ย่อแบบ increase แล้วครอบทิ้ง — ยืดให้พอดีทั้งสองด้านทำให้หน้าคนแบน
    # (เหตุผลเต็มที่ compare._pane ซึ่งเจอปัญหาเดียวกันเป๊ะ)
    def fit(tag):
        return (f"[{tag}]scale={hw}:{hh}:force_original_aspect_ratio=increase"
                f":flags={flags},crop={hw}:{hh},setsar=1")

    # **shortest=0 เขียนไว้ชัด ๆ ทั้งที่เป็นค่าตั้งต้นอยู่แล้ว**
    #
    # คลิปที่สองจะสั้นกว่าที่ต้องใช้เมื่อไรก็ได้ (คนเลือกช่วงท้ายคลิปมาคู่กับช็อต
    # ที่ยาวกว่า) — ค่าตั้งต้นของ vstack คือ *ซ้ำเฟรมสุดท้าย* ของฝั่งที่หมดก่อน
    # ซึ่งตรงกับที่ต้องการพอดี  ส่วน shortest=1 จะตัดทั้งชิ้นให้สั้นตามคลิปที่สอง
    #
    # เขียนไว้เพราะมันคือ *การตัดสินใจ* ไม่ใช่การไม่ได้ตัดสินใจ — ตอนแรกใส่ tpad
    # ไว้ที่สองครึ่งเพื่อ "กัน" เรื่องนี้ แล้ววัดจริงถึงรู้ว่ามันไม่ได้ทำอะไรเลย
    # (อินพุต 8 วิ + 2 วิ ได้ 240 เฟรมเท่ากันทั้งมีและไม่มี tpad)
    stack = ("hstack" if mode == "h" else "vstack") + "=inputs=2:shortest=0"
    return ";".join([
        fit("0:v") + "[sa]",
        fit("1:v") + "[sb]",
        f"[sa][sb]{stack}[sv]",
        f"[sv]{seg_vfilter(f, ctx, frames)}[v]",
        f"[0:a]{seg_afilter(f, dur)}[a]",
    ])


def seg_afilter(f, dur):
    parts = []
    if f.get("mute"):
        parts.append("volume=0")
    else:
        # ปรับดัง/เบาก่อน atempo — atempo ไม่สนใจระดับ ลำดับจึงไม่มีผลต่อผลลัพธ์
        # แต่วางไว้ต้นสายอ่านง่ายกว่า (และ mute ชนะเสมอ ไม่ต้องคูณสองชั้น)
        vol = float(f.get("vol_db", 0.0) or 0.0)
        if abs(vol) > 1e-6:
            parts.append(f"volume={vol:.2f}dB")
    sp = float(f.get("speed", 1.0))
    if abs(sp - 1.0) > 1e-6:
        parts += _atempo(sp)
    # บังคับความยาวให้เท่าภาพเป๊ะ เหมือนขั้น 3 — atempo ปัดเศษของมันเอง
    parts.append("apad")
    parts.append(f"atrim=end={dur:.6f}")
    parts.append("asetpts=PTS-STARTPTS")
    return ",".join(parts)


def seg_key(ctx, src, f, frames):
    """ชื่อไฟล์ = sha1 ของทุกอย่างที่มีผลต่อภาพ/เสียงของชิ้นนี้

    หลักการเดียวกับขั้น 3 เป๊ะ: แก้ค่าไหนก็ตามที่เปลี่ยนผลลัพธ์ → กุญแจเปลี่ยน →
    ไฟล์ใหม่ · แก้ค่าที่ไม่เปลี่ยนผล (เช่นสลับลำดับในไทม์ไลน์) → กุญแจเท่าเดิม →
    ไม่ต้องทำใหม่ · เก็บลายเซ็นของไฟล์ต้นทางไว้ด้วย เพราะ segment ของขั้น 3
    ถูกสร้างใหม่ได้ตลอดถ้ามีคนแก้ค่าฝั่งนั้น
    """
    from .render import encode_args, seg_audio_args
    from .util import key_of
    try:
        st = src.stat()
        sig = [st.st_size, int(st.st_mtime)]
    except OSError:
        sig = [0, 0]
    # อีกครึ่งจอเป็นต้นทางเต็มตัว ไม่ใช่พารามิเตอร์ — ต้องเข้ากุญแจทั้งชื่อและ
    # ลายเซ็นไฟล์ ไม่งั้นแก้คลิปที่สองแล้ว cache ยังคืนของเก่าให้โดยไม่มีใครรู้
    #
    # **ใส่คีย์พวกนี้เฉพาะตอนแบ่งจอจริง ไม่ใช่ใส่ค่าว่างไว้เสมอ** — key_of ทำ
    # json.dumps ทั้งก้อน คีย์ที่ค่าเป็นค่าว่างก็ยังเปลี่ยนสตริงที่เอาไปแฮช
    # ผลคือชิ้นทุกชิ้นของทุกโปรเจกต์ที่มีอยู่ได้กุญแจใหม่พร้อมกัน แล้ว cache
    # ทั้งกองถูกทิ้งตอนอัปเดตเอนจิน โดยที่ไม่มีใครตั้งอะไรใหม่เลยสักค่า
    src2 = pair_path(ctx, f)
    pair = {}
    if src2 is not None:
        try:
            st2 = src2.stat()
            sig2 = [st2.st_size, int(st2.st_mtime)]
        except OSError:
            sig2 = [0, 0]
        pair = {"src2": src2.name, "sig2": sig2,
                "at2": round(float(f.get("split_at", 0.0) or 0.0), 3),
                "fc": seg_complex(ctx, f, frames)}
    return key_of({
        "src": src.name, "sig": sig, "frames": int(frames),
        "vf": seg_vfilter(f, ctx, frames),
        "af": seg_afilter(f, frames / _fps(ctx)),
        "enc": encode_args(ctx, audio=False) + seg_audio_args(ctx),
        "fps": ctx.get("video.fps"),
        **pair,
    })


def _fps(ctx):
    from .render import fps_value
    return fps_value(ctx)


def render_one(ctx, src, f, frames, dst):
    from .render import encode_args, seg_audio_args
    from .util import run as sh
    if dst.exists() and dst.stat().st_size > 1024:
        return True, "cache"
    tmp = part_path(dst, ".mov")
    dur = frames / _fps(ctx)
    src2 = pair_path(ctx, f)
    cmd = ["ffmpeg", "-nostdin", "-hide_banner", "-v", "error", "-y",
           "-i", str(src)]
    if src2 is not None:
        # -ss มาก่อน -i = ค้นหาแบบเร็ว (เลื่อนก่อนถอดรหัส) เหมือนที่ขั้น 3 ทำ
        cmd += ["-ss", f"{float(f.get('split_at', 0.0) or 0.0):.3f}", "-i", str(src2)]
        cmd += ["-filter_complex", seg_complex(ctx, f, frames),
                "-map", "[v]", "-map", "[a]"]
    else:
        # ทางเดิม ไม่แตะ — ชิ้นที่ไม่ได้แบ่งจอต้องได้คำสั่งเดิมทุกตัวอักษร
        cmd += ["-vf", seg_vfilter(f, ctx, frames), "-af", seg_afilter(f, dur)]
    cmd += ["-fps_mode", "cfr", "-r", str(ctx.get("video.fps", "60000/1001")),
           "-t", f"{dur:.6f}",
           "-color_range", "tv", "-colorspace", "bt709",
           "-color_primaries", "bt709", "-color_trc", "bt709"]
    cmd += encode_args(ctx, audio=False) + seg_audio_args(ctx)
    cmd += ["-movflags", "+faststart", str(tmp)]
    r = sh(cmd, check=False)
    if r.returncode != 0 or not tmp.exists():
        tmp.unlink(missing_ok=True)
        return False, r.stderr[-400:]
    tmp.replace(dst)
    return True, "new"


def render(ctx, man):
    """ตัดชิ้นที่ถูกแต่งให้ครบตาม fx-render.json — ชิ้นที่ไม่ได้แตะไม่ต้องทำอะไร"""
    from concurrent.futures import ThreadPoolExecutor
    from .util import Progress, c, info
    # กุญแจซ้ำ = ไฟล์ปลายทางชื่อเดียวกัน ต้องเหลือคิวเดียว ไม่งั้นตัดทับกันแล้วได้
    # ชิ้นที่พัง (เหตุผลเดียวกับ render._dedup — และที่นี่ซ้ำง่ายกว่าอีก เพราะ
    # ชิ้นที่มาจาก segment เดียวกันและตั้งเอฟเฟกต์เหมือนกันย่อมได้กุญแจเท่ากัน)
    seen, todo = set(), []
    for s in man["segments"]:
        if not s["fx"] or (seg_dir(ctx) / s["out"]).exists() or s["out"] in seen:
            continue
        seen.add(s["out"])
        todo.append(s)
    n_fx = sum(1 for s in man["segments"] if s["fx"])
    if not n_fx:
        return
    if not todo:
        info(f"  แต่งชิ้น {n_fx} ชิ้น  ({c('มีครบใน cache แล้ว', 'd')})")
        return
    seg_dir(ctx).mkdir(parents=True, exist_ok=True)
    pr = Progress(len(todo), "แต่งชิ้น")
    failed = []

    def work(s):
        ok, msg = render_one(ctx, ctx.seg_dir / s["file"], s["effects"],
                             s["frames"], seg_dir(ctx) / s["out"])
        return s, ok, msg

    with ThreadPoolExecutor(max_workers=int(ctx.get("render.workers", 2))) as ex:
        for s, ok, msg in ex.map(work, todo):
            if not ok:
                failed.append((s["name"], msg))
            pr.step(f"{s['name']} {_how(s['effects'])}")
    pr.done()
    for name, msg in failed:
        warn(f"แต่งชิ้นไม่สำเร็จ {name}: {msg[:200]}")
    if failed:
        die(f"มี {len(failed)} ชิ้นที่แต่งไม่สำเร็จ")


def _how(f):
    bits = []
    if abs(float(f.get("speed", 1.0)) - 1.0) > 1e-6:
        bits.append(f"{float(f['speed']):g}x")
    z0, z1, moving = _zoom_pair(f)
    if moving and abs(z1 - z0) > 1e-4:
        bits.append(f"ซูม{z0:g}→{z1:g}")
    elif z0 > 1.0 + 1e-6:
        bits.append(f"ซูม{z0:g}")
    if moving and f.get("pan"):
        bits.append({"l": "ไถลซ้าย", "r": "ไถลขวา",
                     "u": "ไถลขึ้น", "d": "ไถลลง"}[str(f["pan"])])
    if float(f.get("glitch", 0.0) or 0.0) > 1e-6:
        bits.append(f"กระตุก{float(f['glitch']):g}")
    if float(f.get("whip", 0.0) or 0.0) > 1e-6:
        bits.append(f"วิป{float(f['whip']):g}")
    if _on_split(f):
        bits.append(("แบ่งบน-ล่าง" if f["split"] == "v" else "แบ่งซ้าย-ขวา")
                    + f" + {f['split_with']}")
    if f.get("grade"):
        bits.append(str(f["grade"]))
    if f.get("mute"):
        bits.append("ปิดเสียง")
    elif abs(float(f.get("vol_db", 0.0) or 0.0)) > 1e-6:
        bits.append(f"{float(f['vol_db']):+g}dB")
    return " ".join(bits)


