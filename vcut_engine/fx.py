def _on_glitch(f):
    return float(f.get("glitch", 0.0) or 0.0) > 1e-6


def _has_room(f):
    """มีที่ให้กล้องไถลไหม — ต้องซูมเข้าไปแล้วถึงจะมีขอบเหลือให้เลื่อน"""
    return max(float(f.get("zoom", 1.0) or 1.0),
               float(f.get("zoom_to", 0.0) or 0.0)) > 1.0 + 1e-6


def _split_mode(f):
    return str(f.get("split", "") or "") in ("v", "h")


def _has_pair(f):
    return bool(str(f.get("split_with", "") or "").strip())


